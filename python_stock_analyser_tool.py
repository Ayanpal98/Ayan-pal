# Validate date to prevent future dates and non-trading days
def is_valid_date(start_date, end_date):
    today = date.today()
    try:
        start = datetime.strptime(start_date, '%Y-%m-%d').date()
        end = datetime.strptime(end_date, '%Y-%m-%d').date()
        if start > today or end > today:
            return False, "Dates cannot be in the future."
        if start >= end:
            return False, "Start date must be before end date."
        # Check if end date is a weekend or likely holiday
        if end.weekday() >= 5:  # Saturday (5) or Sunday (6)
            return False, f"End date {end_date} is a weekend. Choose a weekday."
        # Basic holiday check (e.g., New Year's Day)
        if end.month == 1 and end.day == 1:
            return False, f"End date {end_date} is a market holiday (New Year's Day). Choose another date."
        return True, ""
    except ValueError:
        return False, "Invalid date format. Use YYYY-MM-DD."

